def write_pinmux_ledger(path: Path = PINMUX_LEDGER_JSON) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(build_pinmux_ledger(), indent=2, sort_keys=True) + "\n", encoding="utf-8")


def main() -> int:
    write_pinmux_ledger()
    return 0


