def stm32_assignment(
    *,
    pin_name: str,
    physical_pin: int,
    function: str,
    bus: str,
    source_table: str,
    evidence: str,
    alternate_function: str | None = None,
) -> dict[str, object]:
    assignment: dict[str, object] = {
        "pin_name": pin_name,
        "physical_pin": physical_pin,
        "function": function,
        "bus": bus,
        "source": "STM32U585xx datasheet DS13086 Rev 10",
        "source_table": source_table,
        "evidence": evidence,
        "review_status": "source_backed",
    }
    if alternate_function is not None:
        assignment["alternate_function"] = alternate_function
    return assignment


